--
-- WHY THE ENTITY METADATA UPDATE LANDS ATOMICALLY WITH THE STORED PROCEDURES:
--   Both the Entity.Configuration / TrackRecordChanges flags and the 3-column
--   datestamps_only stored procedures must take effect in the same migration so
--   no host running migrations-only upgrades ever executes a 3-column sproc
--   while EntityInfo.SaveReturnMode is still "full" (which would trigger SQL
--   Server error 213 or wipe in-memory entity fields). metadata/entities/
--   .save-return-datestamps-only.json declares the identical values so the next
--   release Metadata_Sync push stays converged with zero drift.
--
-- ENTITIES COVERED IN THIS MIGRATION (2):
--   - MJ_BizApps_Tasks: Task Activities ([TaskActivity]):
--     spCreateTaskActivity, spUpdateTaskActivity -> [ID], [__mj_CreatedAt], [__mj_UpdatedAt]
--   - MJ_BizApps_Tasks: Task Notification Logs ([TaskNotificationLog]):
--     spCreateTaskNotificationLog, spUpdateTaskNotificationLog -> [ID], [__mj_CreatedAt], [__mj_UpdatedAt]
-- =============================================================================

UPDATE [${mjSchema}].[Entity]
SET
    [TrackRecordChanges] = 0,
    [Configuration] = CASE
        WHEN NULLIF(LTRIM(RTRIM(COALESCE([Configuration], N''))), N'') IS NULL
            THEN N'{
  "SaveReturnMode": "datestamps_only"
}'
        ELSE JSON_MODIFY([Configuration], '$.SaveReturnMode', 'datestamps_only')
    END
WHERE [SchemaName] = '${flyway:defaultSchema}'
  AND [BaseTable] IN ('TaskActivity', 'TaskNotificationLog');
