import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
    mjBizAppsTasksTaskSchema,
    type mjBizAppsTasksTaskEntity,
} from '../index.js';

interface EntityFieldMetadataEntry {
    primaryKey: { ID: string };
    fields: {
        DefaultValue?: string;
        ValueListType?: string;
        Description?: string;
        AutoUpdateDescription?: boolean;
    };
}

interface EntityMetadataEntry {
    primaryKey: { ID: string };
    relatedEntities?: {
        'MJ: Entity Fields'?: EntityFieldMetadataEntry[];
    };
}

interface ActionParamMetadataEntry {
    fields: {
        Name?: string;
        DefaultValue?: string;
        Description?: string;
    };
}

interface ActionMetadataEntry {
    fields?: {
        Name?: string;
    };
    relatedEntities?: {
        'MJ: Action Params'?: ActionParamMetadataEntry[];
    };
}

interface ReleaseLinesManifest {
    next?: {
        edgeOnlyMigrations?: string[];
    };
}

const currentDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(currentDir, '../../../..');

const SQLSERVER_MIGRATION_REL = 'migrations/V202611222115__v1.16.x__Task_Visibility_Team_Organization.sql';
const POSTGRES_MIGRATION_REL = 'migrations-pg/V202611222115__v1.16.x__Task_Visibility_Team_Organization.pg.sql';
const CODEGEN_BANNER = '-- GENERATED BY MemberJunction CodeGen — DO NOT EDIT BY HAND';

function countBlankLinesBeforeCodeGenBanner(sqlText: string): number {
    const lines = sqlText.split(/\r?\n/);
    const bannerIdx = lines.findIndex((line) => line.includes(CODEGEN_BANNER));
    if (bannerIdx < 0) return -1;

    let blankCount = 0;
    for (let i = bannerIdx - 1; i >= 0; i--) {
        if (lines[i].trim() === '' || lines[i].trim() === '-- =============================================================================') {
            if (lines[i].trim() === '') {
                blankCount++;
            }
        } else {
            break;
        }
    }
    return blankCount;
}

describe('Slice 1: Task.Visibility (Team, Private, Organization) dual-dialect migration & metadata', () => {
    it('ships SQL Server and PostgreSQL additive migrations with >= 50 blank lines before CodeGen block', () => {
        const sqlServerPath = resolve(repoRoot, SQLSERVER_MIGRATION_REL);
        const postgresPath = resolve(repoRoot, POSTGRES_MIGRATION_REL);

        expect(existsSync(sqlServerPath)).toBe(true);
        expect(existsSync(postgresPath)).toBe(true);

        const tsql = readFileSync(sqlServerPath, 'utf8');
        const pgsql = readFileSync(postgresPath, 'utf8');

        expect(countBlankLinesBeforeCodeGenBanner(tsql)).toBeGreaterThanOrEqual(50);
        expect(countBlankLinesBeforeCodeGenBanner(pgsql)).toBeGreaterThanOrEqual(50);

        // SQL Server catalog lookups, backfill before CHECK creation, new default & CHECK, no prune proc
        expect(tsql).toContain('sys.default_constraints');
        expect(tsql).toContain('sys.check_constraints');
        expect(tsql).toContain("NOT IN (N'Team', N'Private', N'Organization')");
        expect(tsql).toContain("DEFAULT (N'Team') FOR [Visibility]");
        expect(tsql).toContain("CHECK ([Visibility] IN ('Team', 'Private', 'Organization'))");
        expect(tsql).toContain("ISNULL(@Visibility, 'Team')");
        expect(tsql).not.toMatch(/\bspDeleteUnneededEntityFields\b/i);

        const tsqlDropIdx = tsql.indexOf('sys.check_constraints');
        const tsqlBackfillIdx = tsql.indexOf("SET [Visibility] = N'Team'");
        const tsqlAddCheckIdx = tsql.indexOf("ADD CONSTRAINT [CK_Task_Visibility]");
        expect(tsqlDropIdx).toBeGreaterThan(-1);
        expect(tsqlBackfillIdx).toBeGreaterThan(tsqlDropIdx);
        expect(tsqlAddCheckIdx).toBeGreaterThan(tsqlBackfillIdx);

        // PostgreSQL constraint drops, backfill before CHECK creation, new default & CHECK
        expect(pgsql).toContain('DROP CONSTRAINT IF EXISTS "CK_Task_Visibility"');
        expect(pgsql).toContain('ALTER COLUMN "Visibility" DROP DEFAULT');
        expect(pgsql).toContain("NOT IN ('Team', 'Private', 'Organization')");
        expect(pgsql).toContain("ALTER COLUMN \"Visibility\" SET DEFAULT 'Team'");
        expect(pgsql).toContain('CHECK ("Visibility" IN (\'Team\', \'Private\', \'Organization\'))');
        expect(pgsql).toContain("COALESCE(p_Visibility, 'Team')");

        const pgDropIdx = pgsql.indexOf('DROP CONSTRAINT IF EXISTS "CK_Task_Visibility"');
        const pgBackfillIdx = pgsql.indexOf('SET "Visibility" = \'Team\'');
        const pgAddCheckIdx = pgsql.indexOf('ADD CONSTRAINT "CK_Task_Visibility"');
        expect(pgDropIdx).toBeGreaterThan(-1);
        expect(pgBackfillIdx).toBeGreaterThan(pgDropIdx);
        expect(pgAddCheckIdx).toBeGreaterThan(pgBackfillIdx);
    });

    it('updates Task.Visibility metadata in entities, actions, and edgeOnlyMigrations', () => {
        const entitiesRaw = readFileSync(resolve(repoRoot, 'metadata/entities/.entities.json'), 'utf8');
        const entities = JSON.parse(entitiesRaw) as EntityMetadataEntry[];
        const tasksEntity = entities.find(
            (e) => e.primaryKey.ID === '@lookup:MJ: Entities.Name=MJ_BizApps_Tasks: Tasks',
        );
        expect(tasksEntity).toBeDefined();

        const visField = tasksEntity?.relatedEntities?.['MJ: Entity Fields']?.find(
            (f) => f.primaryKey.ID === '@lookup:MJ: Entity Fields.Name=Visibility&EntityID=@parent:ID',
        );
        expect(visField).toBeDefined();
        expect(visField?.fields.DefaultValue).toBe('Team');
        expect(visField?.fields.ValueListType).toBe('List');
        expect(visField?.fields.AutoUpdateDescription).toBe(false);
        expect(visField?.fields.Description).toContain('Team');
        expect(visField?.fields.Description).toContain('Private');
        expect(visField?.fields.Description).toContain('Organization');

        const actionsRaw = readFileSync(resolve(repoRoot, 'metadata/actions/.tasks-actions.json'), 'utf8');
        const actions = JSON.parse(actionsRaw) as ActionMetadataEntry[];
        const createTask = actions.find((a) => a.fields?.Name === 'Create Task');
        const createVis = createTask?.relatedEntities?.['MJ: Action Params']?.find(
            (p) => p.fields.Name === 'Visibility',
        );
        expect(createVis?.fields.DefaultValue).toBe('Team');
        expect(createVis?.fields.Description).toContain('Organization');

        const releaseLines = JSON.parse(
            readFileSync(resolve(repoRoot, 'release-lines.json'), 'utf8'),
        ) as ReleaseLinesManifest;
        expect(releaseLines.next?.edgeOnlyMigrations).toContain(
            'V202611222115__v1.16.x__Task_Visibility_Team_Organization.sql',
        );
    });

    it('accepts Team | Private | Organization with default Team and rejects Standard in Zod & TypeScript types', () => {
        const visibilitySchema = mjBizAppsTasksTaskSchema.shape.Visibility;

        expect(visibilitySchema.parse(undefined)).toBe('Team');
        expect(visibilitySchema.parse('Team')).toBe('Team');
        expect(visibilitySchema.parse('Private')).toBe('Private');
        expect(visibilitySchema.parse('Organization')).toBe('Organization');

        expect(visibilitySchema.safeParse('Standard').success).toBe(false);
        expect(visibilitySchema.safeParse('Public').success).toBe(false);
        expect(visibilitySchema.safeParse('').success).toBe(false);
        expect(visibilitySchema.safeParse(null).success).toBe(false);

        const allowedValues: ReadonlyArray<mjBizAppsTasksTaskEntity['Visibility']> = [
            'Team',
            'Private',
            'Organization',
        ];
        expect(allowedValues).toHaveLength(3);

        const entitySource = readFileSync(
            resolve(repoRoot, 'packages/Entities/src/generated/entities/__mj_BizAppsTasks.ts'),
            'utf8',
        );
        expect(entitySource).toContain("get Visibility(): 'Organization' | 'Private' | 'Team'");
        expect(entitySource).toContain("set Visibility(value: 'Organization' | 'Private' | 'Team')");
    });
});
