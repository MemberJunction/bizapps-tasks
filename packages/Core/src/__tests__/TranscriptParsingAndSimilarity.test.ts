import { describe, it, expect } from 'vitest';
import type { UserInfo } from '@memberjunction/core';
import { RegisterClass } from '@memberjunction/global';
import {
    computeTaskTextSimilarity,
    deduplicateCommitmentsAgainstTasks,
    extractDecisionsFromText,
    normalizeTranscriptText,
    parseSrtTranscript,
    parseWebVttTranscript,
    rankSimilarTasks,
    ResolveTranscriptSource,
    tokenizeTaskText,
    TranscriptSourceBase,
    type FetchedTranscript,
    type TranscriptMeetingContext,
    type TranscriptReference,
    type TranscriptSourceContext,
} from '../meetings/index.js';

@RegisterClass(TranscriptSourceBase, 'UnitTestMockTranscriptSource')
class MockTranscriptSource extends TranscriptSourceBase {
    private configured = false;
    public async Initialize(_ctx: TranscriptSourceContext, _user: UserInfo): Promise<void> {
        this.configured = true;
    }
    public get IsConfigured(): boolean {
        return this.configured;
    }
    public async FindTranscript(meeting: TranscriptMeetingContext): Promise<TranscriptReference | null> {
        return meeting.ProviderMeetingID
            ? { SourceKey: 'UnitTestMockTranscriptSource', ExternalTranscriptID: meeting.ProviderMeetingID }
            : null;
    }
    public async FetchTranscript(reference: TranscriptReference): Promise<FetchedTranscript> {
        return {
            Reference: reference,
            PlainText: 'Alice: Let us ship the release Friday.',
            Speakers: ['Alice'],
        };
    }
}

describe('Transcript Parsing', () => {
    it('parses WebVTT with voice tags, speaker prefixes, NOTE blocks, and consecutive speaker merging', () => {
        const vtt = `WEBVTT

NOTE Generated by Zoom Cloud Recording

1
00:00:01.000 --> 00:00:04.500
<v Alice Chen>Welcome everyone to the Q4 sync.</v>

2
00:00:04.600 --> 00:00:08.000
<v Alice Chen>Let us review the launch checklist.</v>

3
00:00:09.000 --> 00:00:12.000
Bob Rivera: DECISION: Ship v6.3 on Friday morning.

4
00:00:13.000 --> 00:00:16.000
Bob Rivera: ACTION: Alice Chen to send the board deck by Thursday.
`;

        const parsed = parseWebVttTranscript(vtt);
        expect(parsed.Format).toBe('vtt');
        expect(parsed.Speakers).toEqual(['Alice Chen', 'Bob Rivera']);
        expect(parsed.Turns).toHaveLength(2);
        expect(parsed.Turns[0]).toEqual({
            Speaker: 'Alice Chen',
            Text: 'Welcome everyone to the Q4 sync. Let us review the launch checklist.',
        });
        expect(parsed.PlainText).toContain('Alice Chen: Welcome everyone');
        expect(parsed.PlainText).toContain('Bob Rivera: DECISION: Ship v6.3 on Friday morning.');
    });

    it('parses SRT transcripts and strips numeric cue counters and timestamps', () => {
        const srt = `1
00:00:01,000 --> 00:00:03,500
Carol: First point on the roadmap.

2
00:00:04,000 --> 00:00:07,000
Dave: AGREED: Freeze scope after Tuesday.
`;
        const parsed = parseSrtTranscript(srt);
        expect(parsed.Format).toBe('srt');
        expect(parsed.Speakers).toEqual(['Carol', 'Dave']);
        expect(parsed.PlainText).toBe(
            'Carol: First point on the roadmap.\nDave: AGREED: Freeze scope after Tuesday.',
        );
    });

    it('auto-detects JSON segment payloads and plain text in normalizeTranscriptText', () => {
        const jsonRaw = JSON.stringify({
            segments: [
                { speaker: 'Maya', text: 'Let us finalize billing.' },
                { speaker: 'Maya', text: 'We need invoices out Friday.' },
                { speaker: 'Liam', text: 'I will draft them.' },
            ],
        });
        const fromJson = normalizeTranscriptText(jsonRaw);
        expect(fromJson.Speakers).toEqual(['Maya', 'Liam']);
        expect(fromJson.Turns).toHaveLength(2);
        expect(fromJson.PlainText).toContain('Maya: Let us finalize billing. We need invoices out Friday.');

        const plain = normalizeTranscriptText('ACTION: Send Q4 deck to Amith');
        expect(plain.Format).toBe('text');
        expect(plain.Speakers).toEqual([]);
        expect(plain.PlainText).toBe('ACTION: Send Q4 deck to Amith');
    });

    it('extracts unique explicit decisions from spoken and markdown lines', () => {
        const text = [
            'Alice: DECISION: Standardize on typed actions for Chief of Staff.',
            '- DECIDED: Defer Slack raw huddle audio until API exists.',
            'AGREED: Standardize on typed actions for Chief of Staff.',
            'ACTION: Create follow-up ticket.',
        ].join('\n');

        expect(extractDecisionsFromText(text)).toEqual([
            'Standardize on typed actions for Chief of Staff.',
            'Defer Slack raw huddle audio until API exists.',
        ]);
    });
});

describe('Task Text Similarity & Commitment Deduplication', () => {
    it('tokenizes text cleanly and computes exact, substring, and Jaccard similarity', () => {
        expect(tokenizeTaskText('Send the Q4 board deck to Amith!')).toEqual(
            new Set(['send', 'q4', 'board', 'deck', 'amith']),
        );
        expect(computeTaskTextSimilarity('Send Q4 board deck', 'send q4 board deck!')).toBe(1);
        expect(
            computeTaskTextSimilarity('Send Q4 board deck', 'Send Q4 board deck to Amith before Friday'),
        ).toBeGreaterThan(0.6);
        expect(computeTaskTextSimilarity('Renew office lease', 'Fix database migration index')).toBeLessThan(0.2);
    });

    it('blends lexical, semantic, and assignee signals when ranking similar tasks', () => {
        const candidates = [
            {
                ID: '11111111-1111-4111-8111-111111111111',
                Name: 'Prepare quarterly executive slides',
                Description: 'Compile Q4 financial highlights for the board',
                Status: 'Open',
                AssigneePersonIDs: ['aaaa1111-1111-4111-8111-111111111111'],
            },
            {
                ID: '22222222-2222-4222-8222-222222222222',
                Name: 'Order new monitor cables',
                Description: 'USB-C cables for conference room',
                Status: 'Open',
                AssigneePersonIDs: ['bbbb2222-2222-4222-8222-222222222222'],
            },
        ];

        const semanticScores = new Map<string, number>([
            ['11111111-1111-4111-8111-111111111111', 0.88],
        ]);

        const matches = rankSimilarTasks('Send Q4 board deck slides', candidates, {
            semanticScoresByTaskID: semanticScores,
            preferredAssigneePersonID: 'aaaa1111-1111-4111-8111-111111111111',
            minScore: 0.35,
            limit: 5,
        });

        expect(matches).toHaveLength(1);
        expect(matches[0].TaskID).toBe('11111111-1111-4111-8111-111111111111');
        expect(matches[0].Score).toBeGreaterThan(0.5);
        expect(matches[0].MatchReason).toContain('semantic vector similarity');
        expect(matches[0].MatchReason).toContain('same assignee');
    });

    it('deduplicates commitments against existing tasks in the 30-day window', () => {
        const existingTasks = [
            {
                ID: '11111111-1111-4111-8111-111111111111',
                Name: 'Send Q4 board deck to Amith',
                Description: 'Include revised ARR forecast',
                Status: 'InProgress',
                DueAt: '2026-11-25T17:00:00.000Z',
            },
        ];

        const commitments = [
            {
                ProposalID: 'proposal-1',
                Title: 'Send Q4 board deck to Amith',
                AssigneePersonID: null,
                AssigneeName: 'Alice Chen',
            },
            {
                ProposalID: 'proposal-2',
                Title: 'Schedule security penetration test with external vendor',
                AssigneePersonID: null,
                AssigneeName: 'Bob Rivera',
            },
        ];

        const result = deduplicateCommitmentsAgainstTasks(commitments, existingTasks);
        expect(result.MatchedExistingTasks).toHaveLength(1);
        expect(result.MatchedExistingTasks[0].ProposalID).toBe('proposal-1');
        expect(result.MatchedExistingTasks[0].MatchedTask.TaskID).toBe(
            '11111111-1111-4111-8111-111111111111',
        );
        expect(result.ProposedNewCommitments).toHaveLength(1);
        expect(result.ProposedNewCommitments[0].ProposalID).toBe('proposal-2');
    });
});

describe('TranscriptSourceBase & ResolveTranscriptSource', () => {
    it('resolves registered TranscriptSourceBase plugins via ClassFactory', async () => {
        expect(MockTranscriptSource).toBeDefined();
        const alice = { ID: 'user-alice', Name: 'Alice', Email: 'alice@example.com' } as unknown as UserInfo;
        const src = ResolveTranscriptSource('UnitTestMockTranscriptSource');
        expect(src).not.toBeNull();
        await src!.Initialize({}, alice);
        expect(src!.IsConfigured).toBe(true);

        const ref = await src!.FindTranscript(
            {
                Title: 'Weekly Sync',
                StartsAt: new Date(),
                EndsAt: new Date(),
                ProviderMeetingID: 'zoom-123',
            },
            alice,
        );
        expect(ref?.ExternalTranscriptID).toBe('zoom-123');

        const fetched = await src!.FetchTranscript(ref!, alice);
        expect(fetched.PlainText).toContain('ship the release Friday');
    });
});
